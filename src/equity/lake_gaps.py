"""Data gaps measured in the lake itself, not in the configs.

`equity.gaps` says what each config *maps*; a mapped field can still be empty in the data, a
registered source can be unbuilt, and a statewide layer can skip counties. This reads each
source's `_state.json` bundle from object storage (part counts, and the county each part
covers) and reports what was actually written:

    uv run python -m equity.lake_gaps > reports/lake_gaps.md

Fill rates are rows written / parcels. The adapters write an owner row only when an owner name
exists and an assessment row only when a value and a tax year exist, so a 0% rate means the
field is empty (or unmapped) for that layer. Address rows count situs and mailing addresses.
"""

from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from collections.abc import Iterable, Mapping
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass, field
from typing import Any

from equity.geo import counties

LOW = 0.05  # below this share of parcels a field counts as missing
PARTIAL = 0.6


@dataclass
class Fill:
    parcels: int = 0
    owners: int = 0
    values: int = 0
    addresses: int = 0

    def add(self, counts: Mapping[str, int]) -> None:
        self.parcels += int(counts.get("parcel", 0))
        self.owners += int(counts.get("owner_snapshot", 0))
        self.values += int(counts.get("parcel_assessment", 0))
        self.addresses += int(counts.get("address", 0))

    def share(self, n: int) -> float:
        return n / self.parcels if self.parcels else 0.0


@dataclass
class LayerGaps:
    source_id: str
    fill: Fill
    by_county: dict[str, Fill] = field(default_factory=dict)  # fips5 -> fill (when split)


def parse_bundle(source_id: str, bundle: Mapping[str, str], state_fips: str) -> LayerGaps:
    """One source's `_state.json` (relative path -> file text) as fill counts, total and, when
    its parts are planned per county (`county_fips` param), per county."""
    total = Fill()
    if "_counts.json" in bundle:
        total.add(json.loads(bundle["_counts.json"]))
    by_county: dict[str, Fill] = {}
    for name, text in bundle.items():
        if not name.startswith("_parts/"):
            continue
        part = json.loads(text)
        fips3 = (part.get("params") or {}).get("county_fips")
        if fips3 is None:
            by_county = {}
            break
        by_county.setdefault(state_fips + str(fips3).zfill(3), Fill()).add(part["counts"])
    return LayerGaps(source_id, total, by_county)


def _pct(x: float) -> str:
    return f"{x:.0%}"


def render(
    registered: Iterable[str],
    bundles: Mapping[str, Mapping[str, str] | None],
) -> str:
    """Markdown report. `bundles` maps every source id found in storage to its bundle (None
    when the source has no bundle yet)."""
    names = {c.fips5: c.name for c in counties()}
    by_state: dict[str, list[str]] = defaultdict(list)
    fips_of: dict[str, str] = {}
    for county in counties():
        by_state[county.state].append(county.fips5)
        fips_of[county.state] = county.state_fips
    built = {s for s, b in bundles.items() if b and "_counts.json" in b}
    reg = sorted(set(registered))
    lines = ["# Gaps in the lake", "",
             "Generated by `uv run python -m equity.lake_gaps` from the `_state.json` bundles in "
             "object storage. Fill = rows written / parcels (owner rows exist only when a name "
             "exists; value rows only when a value and tax year exist).", ""]  # fmt: skip

    unbuilt = [s for s in reg if s not in built]
    kinds = Counter(s.rsplit(".", 1)[-1] for s in unbuilt)
    lines += [f"## Registered but not built: {len(unbuilt)} of {len(reg)}", "",
              ", ".join(f"{k} ({n})" for k, n in kinds.most_common()), "",
              "<details><summary>Source ids</summary>", "",
              " ".join(f"`{s}`" for s in unbuilt), "", "</details>", ""]  # fmt: skip
    orphans = sorted(s for s in built if s not in set(reg) and "." in s and s != "test.tiny")
    if orphans:
        lines += ["## Built but no longer registered", "", " ".join(f"`{s}`" for s in orphans), ""]

    layers: dict[str, LayerGaps] = {}
    for sid in sorted(built):
        if sid.endswith(".parcels"):
            st = sid.split(".")[0].upper()
            bundle = bundles[sid]
            assert bundle is not None
            layers[sid] = parse_bundle(sid, bundle, fips_of.get(st, "00"))

    lines += ["## Parcel layers with an empty field", "",
              "| Layer | Parcels | Owner | Value | Address |", "|---|---|---|---|---|"]  # fmt: skip
    for sid, g in layers.items():
        f = g.fill
        shares = (f.share(f.owners), f.share(f.values), f.share(f.addresses))
        if min(shares) < PARTIAL:
            lines.append(
                f"| `{sid}` | {f.parcels:,} | " + " | ".join(_pct(x) for x in shares) + " |"
            )
    lines.append("")

    lines += ["## Counties by state", "",
              "Owners: counties where some loaded layer has owner names on at least 5% of parcels.",
              "", "| State | Counties with owners | Missing from every layer | No owners | "
              "No values |", "|---|---|---|---|---|"]  # fmt: skip
    for st in sorted(by_state):
        all_c = by_state[st]
        seen: set[str] = set()
        owned: set[str] = set()
        valued: set[str] = set()
        for sid, g in layers.items():
            if sid.split(".")[0].upper() != st:
                continue
            per = g.by_county
            if not per and ".statewide." not in sid:  # a county layer covers its own county
                per = _county_layer(sid, g, all_c, names)
            elif not per:  # statewide, not split by county: assume all counties
                per = {fips: g.fill for fips in all_c}
            for fips, f in per.items():
                if f.parcels:
                    seen.add(fips)
                    if f.share(f.owners) >= LOW:
                        owned.add(fips)
                    if f.share(f.values) >= LOW:
                        valued.add(fips)
        missing = [names[c] for c in all_c if c not in seen]
        no_own = [names[c] for c in all_c if c in seen and c not in owned]
        no_val = [names[c] for c in all_c if c in seen and c not in valued]
        lines.append(f"| {st} | {len(owned)} of {len(all_c)} | {_short(missing, len(all_c))} | "
                     f"{_short(no_own, len(all_c))} | {_short(no_val, len(all_c))} |")  # fmt: skip
    return "\n".join(lines) + "\n"


def _county_layer(
    sid: str, g: LayerGaps, all_c: list[str], names: Mapping[str, str]
) -> dict[str, Fill]:
    """A county layer's own county, found by its source-id slug (`pa.allegheny.parcels`)."""
    slug = sid.split(".")[1].replace("_", "").lower()

    def norm(text: str) -> str:
        return "".join(ch for ch in text.lower() if ch.isalnum())

    full = {norm(names[c]): c for c in all_c}  # "baltimorecity", "stlouiscounty"
    if slug in full:
        return {full[slug]: g.fill}
    for c in all_c:  # "allegheny" -> Allegheny County, "eastbatonrouge" -> ... Parish
        n = names[c].lower()
        for suffix in (" county", " parish", " borough", " city", " municipality",
                       " census area", " city and borough"):  # fmt: skip
            n = n.removesuffix(suffix)
        if norm(n) == slug:
            return {c: g.fill}
    return {}


def _short(items: list[str], total: int) -> str:
    if not items:
        return "—"
    if len(items) == total:
        return "all"
    shown = ", ".join(i.removesuffix(" County") for i in items[:40])
    return f"{len(items)}: {shown}" + (" …" if len(items) > 40 else "")


def fetch_bundles(store: Any, workers: int = 16) -> dict[str, dict[str, str] | None]:
    _, dirs = store.list_dir("")

    def one(sid: str) -> tuple[str, dict[str, str] | None]:
        try:
            return sid, json.loads(store.download(f"{sid}/_state.json"))
        except Exception:
            return sid, None

    with ThreadPoolExecutor(workers) as ex:
        return dict(ex.map(one, dirs))


def main() -> int:  # pragma: no cover - network
    import os

    from equity.adapters.registry import REGISTRY
    from equity.lake_sync import DEFAULT_URL, Store

    store = Store(
        base_url=os.environ.get("SUPABASE_STORAGE_URL", DEFAULT_URL),
        key=os.environ.get("SUPABASE_SECRET_KEY") or None,
        log=lambda _m: None,
    )
    sys.stdout.write(render([c.source_id for c in REGISTRY], fetch_bundles(store)))
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
