"""Generate docs/coverage.md: what parcel data exists for each state, from the configs.

uv run python -m equity.coverage > docs/coverage.md
"""

from __future__ import annotations

import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import yaml

from equity.adapters.state_parcels import StateConfig, config_paths, load_config
from equity.config import CONFIG_DIR
from equity.geo import counties

NOTES = CONFIG_DIR / "coverage_notes.yaml"
# 50 states + DC, in USPS order of the Census table.
STATES = tuple(sorted({c.state for c in counties()} - {"PR", "AS", "GU", "MP", "VI", "UM"}))


# Hand-written (non-config) statewide parcel adapters: (source_id, owner, values, mailing).
HAND_WRITTEN: dict[str, tuple[str, bool, bool, bool]] = {
    "WV": ("wv.statewide.parcels", True, True, True),
}


@dataclass(frozen=True)
class Row:
    state: str
    sources: tuple[str, ...]
    owner: bool
    values: bool
    mailing: bool
    restrictions: tuple[str, ...]
    note: str


def _has(cfg: StateConfig, *keys: str) -> bool:
    return any(k in cfg.fields for k in keys)


def rows(configs: list[StateConfig], notes: dict[str, str]) -> list[Row]:
    by_state: dict[str, list[StateConfig]] = defaultdict(list)
    for cfg in configs:
        by_state[cfg.state].append(cfg)
    out = []
    for st in STATES:
        cfgs = sorted(by_state.get(st, []), key=lambda c: c.source_id)
        hand = HAND_WRITTEN.get(st)
        out.append(Row(
            state=st,
            sources=tuple(c.source_id for c in cfgs) + ((hand[0],) if hand else ()),
            owner=any(_has(c, "owner1") for c in cfgs) or bool(hand and hand[1]),
            values=any(_has(c, "total_value", "assessed_value", "land_value") for c in cfgs)
            or bool(hand and hand[2]),
            mailing=any(_has(c, "mail_line1", "mail_full", "mail_city") for c in cfgs)
            or bool(hand and hand[3]),
            restrictions=tuple(sorted({r for c in cfgs for r in c.use_restrictions})),
            note=notes.get(st, ""),
        ))  # fmt: skip
    return out


def render(table: list[Row]) -> str:
    def yn(flag: bool) -> str:
        return "yes" if flag else "no"

    built = [r for r in table if r.sources]
    full = [r for r in built if r.owner and r.values]
    lines = [
        "# Parcel coverage by state",
        "",
        "Generated by `uv run python -m equity.coverage` from `config/states/`, "
        "`config/counties/` and `config/coverage_notes.yaml`. Do not edit by hand.",
        "",
        f"- States/DC with at least one adapter: **{len(built)} of {len(table)}**",
        f"- With owner names and values: **{len(full)}**",
        "",
        "| State | Adapters | Owner | Values | Mailing | Use restrictions | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in table:
        srcs = "<br>".join(f"`{s}`" for s in r.sources) or "none"
        lines.append(
            f"| {r.state} | {srcs} | {yn(r.owner)} | {yn(r.values)} | {yn(r.mailing)} | "
            f"{', '.join(r.restrictions) or ''} | {r.note} |"
        )
    return "\n".join(lines) + "\n"


def main(notes_path: Path = NOTES) -> int:
    notes = yaml.safe_load(notes_path.read_text()) if notes_path.exists() else {}
    # Bulk-file parcel adapters (e.g. Texas county zips) use the same config format.
    paths = [*config_paths(), *sorted((CONFIG_DIR / "bulk").glob("*.yaml"))]
    configs = [load_config(p) for p in paths]
    sys.stdout.write(render(rows(configs, notes or {})))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
